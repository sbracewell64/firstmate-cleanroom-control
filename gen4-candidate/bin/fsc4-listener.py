#!/usr/bin/env python3
"""Generate, install, register and verify the clean-room control listener. Generation 3.

Generation 2 (frozen) generated ONE artifact from the canonical configuration: a
watcher custom check that looked for rulings on requests FirstMate had emitted.
Two facts made that insufficient (control issue #3, unattended_monitoring):
upstream keeps no watcher alive for a bare custom check, and nothing looked for
Browser Sol -> FirstMate commissions at all. Generation 3 generates TWO artifacts
from the SAME owner, still authoring no identity of its own:

  1. the check script (unchanged in law; now points at the generation-3 control
     root so it names rulings for generation-3 live requests), and
  2. an inbound process-event EXTENSION binding + source registration, through
     upstream's supported trusted-extension seam (docs/extension-bindings.md):
     the package listener/ is bound into the home (content-addressed, digest
     pinned) and one source '<listener.id>-inbound' is registered with
     config_ref 'fm-home:<FM_HOME>'. A registered source is what upstream's
     supervision predicate counts, so the Stop-owned auto-arm keeps a watcher
     alive for this home even with an empty fleet, and reconcile restarts the
     poll every cycle. The adapter resolves the venue through THIS resolver at
     every poll via the listener record; it names nothing itself.

The canonical control configuration is UNCHANGED by generation 4: the extension
identity is DERIVED from control_config.listener.id, so control_config_generation
does not move.

Usage:
  fsc4-listener.py install     write the check script and the listener record
  fsc4-listener.py register    install, then register the check through upstream fm-check-register.sh,
                               bind the inbound extension, and register its source
  fsc4-listener.py verify      re-derive every artifact and refuse on any drift; check the binding,
                               the registration and the supervision predicate
  fsc4-listener.py show        the resolved listener binding, extension and source identities
  fsc4-listener.py retire-gen2 unregister the generation-2 custom check (same id) so one owner polls
"""
import hashlib
import json
import os
import shutil
import stat
import subprocess
import sys

import fsc4_config

UPSTREAM = os.environ.get("FSC3_UPSTREAM_ROOT", "/mnt/e/FirstMate-Cleanroom/upstream/firstmate")
CTL = fsc4_config.CONTROL_ROOT
PACKAGE_SRC = os.path.join(CTL, "listener")
EXTENSION_ID = "org.firstmate.cleanroom.control-listener"
# The bind source must be on a filesystem with real modes (the host refuses
# group/world-writable package paths, and drvfs reports 777); the authoritative
# bytes stay in the evidence tree and are digest-compared with the staged copy.
PACKAGE_STAGE = os.path.join(os.path.expanduser("~"), ".local", "share", "firstmate-packages", "cleanroom-control-listener-gen3")

CHECK_TEMPLATE = '''#!/usr/bin/env bash
# GENERATED by fsc4-listener.py from the canonical control configuration.
# Do not edit: fsc4-listener.py verify re-derives this file and refuses on drift.
#
# This script names NO repository and NO protocol of its own. Both are resolved
# through the single deterministic resolver at every poll, and the venue
# isolation predicate is re-run here rather than assumed from the value just
# read, so the listener cannot be pointed at the retired venue by editing it.
#
# Three-valued by construction. Silence means "polled, nothing to report".
# An unreadable or invalid configuration is COULD-NOT-OBSERVE and says so out
# loud; it never falls back to a remembered venue and never exits quietly, which
# would be indistinguishable from a clean poll.
#
# GENERATION 4: the ongoing inbound monitor is the registered process-event
# source '<listener.id>-inbound' (see fsc4-listener.py); this check remains the
# ruling poll for generation-3 live outbound requests and runs on the watcher
# that source keeps alive.
set -u
RES={resolver}
CTL={control_root}
if [ ! -r "$RES" ]; then
  echo "fsc3 CNO: control resolver unreadable at $RES; no venue was resolved and nothing was polled"
  exit 0
fi
if ! REPO=$(python3 "$RES" get control.repository 2>&1); then
  echo "fsc3 CNO: control configuration did not resolve control.repository; nothing was polled"
  exit 0
fi
if ! PROTO=$(python3 "$RES" get control.protocol 2>&1); then
  echo "fsc3 CNO: control configuration did not resolve control.protocol; nothing was polled"
  exit 0
fi
if ! python3 "$RES" isolate "$REPO" "$PROTO" >/dev/null 2>&1; then
  echo "fsc3 CNO: venue isolation denied the resolved venue; nothing was polled"
  exit 0
fi
for live in "$CTL"/state/live/*.json; do
  [ -e "$live" ] || continue
  num=$(jq -r '.issue_number' "$live" 2>/dev/null) || continue
  rid=$(jq -r '.request_id' "$live" 2>/dev/null) || continue
  [ -n "$num" ] && [ "$num" != null ] || continue
  # gh api, never a truncating surface: an authority-bearing body read through a
  # ~4 KB surface was not seen whole, and every envelope here exceeds that bound.
  if ! body=$(gh api --paginate "repos/$REPO/issues/$num/comments" --jq '.[] | .body' 2>&1); then
    echo "fsc3 CNO: forge unreachable for $REPO#$num; the ruling universe was not observed"
    continue
  fi
  hits=$(printf '%s' "$body" | grep -Fc -- "$rid") || hits=0
  [ "$hits" -gt 0 ] && echo "fsc3 ruling candidate for $rid on $REPO#$num"
done
exit 0
'''


def render_check():
    return CHECK_TEMPLATE.format(
        resolver=os.path.join(os.path.dirname(os.path.abspath(__file__)), "fsc4_config.py"),
        control_root=CTL,
    )


def sha_file(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def package_digest_rows():
    rows = {}
    for name in sorted(os.listdir(PACKAGE_SRC)):
        p = os.path.join(PACKAGE_SRC, name)
        if os.path.isfile(p):
            rows[name] = sha_file(p)
    return rows


def identities(binding):
    return {
        "source_id": binding["id"] + "-inbound",
        "adapter": binding["id"] + "-inbound",
        "extension_id": EXTENSION_ID,
        "config_ref": "fm-home:" + binding["home"],
        "package_source": PACKAGE_SRC,
        "package_stage": PACKAGE_STAGE,
        "ledger_dir": os.path.join(binding["home"], "state", binding["id"] + ".inbound"),
    }


def render_record(binding, check_sha):
    gen, _cfg, _norm = fsc4_config.generation()
    ids = identities(binding)
    return json.dumps({
        "record": "fm-cleanroom-control-listener/v3",
        "generated_by": "artifacts/control/gen3/bin/fsc4-listener.py",
        "identity_source": (
            "control_config.listener -- the canonical configuration owns the id and both paths; "
            "the inbound source and adapter names are DERIVED from that id; this record carries "
            "no independent copy and is regenerated, never edited"),
        "listener_id": binding["id"],
        "record_path": binding["record_path"],
        "check_script_path": binding["check_script_path"],
        "inbound_source_id": ids["source_id"],
        "inbound_adapter": ids["adapter"],
        "inbound_extension_id": EXTENSION_ID,
        "inbound_config_ref": ids["config_ref"],
        "inbound_package_files_sha256": package_digest_rows(),
        "venue_source": "resolved at every poll through the single canonical resolver, never named in this file",
        "resolver": fsc4_config.__file__,
        "resolver_digest": fsc4_config.resolver_digest(),
        "control_config_owner": fsc4_config.OWNER_PATH,
        "control_config_generation": gen["digest"],
        "schema_generation": 3,
        "schema_sha256": fsc4_config.schema_digest(),
        "check_script_sha256": check_sha,
        "unreadable_config_behaviour": (
            "COULD-NOT-OBSERVE, reported out loud, nothing polled. Never a fallback venue and "
            "never a silent exit, which would be indistinguishable from a clean poll."),
    }, indent=2, sort_keys=True) + "\n"


def install():
    binding = fsc4_config.listener_binding()
    check_path = binding["check_script_abspath"]
    rec_path = binding["record_abspath"]
    for path in (check_path, rec_path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
    body = render_check()
    if os.path.islink(check_path):
        raise SystemExit("REFUSED: %s is a symlink" % check_path)
    with open(check_path, "w", encoding="utf-8") as fh:
        fh.write(body)
    os.chmod(check_path, 0o700)
    check_sha = hashlib.sha256(body.encode("utf-8")).hexdigest()
    with open(rec_path, "w", encoding="utf-8") as fh:
        fh.write(render_record(binding, check_sha))
    os.chmod(rec_path, 0o600)
    return binding, check_path, rec_path, check_sha


def stage_package():
    """Copy the package to an ext4 path with sane modes; digest-compare afterwards."""
    if os.path.isdir(PACKAGE_STAGE):
        shutil.rmtree(PACKAGE_STAGE)
    os.makedirs(PACKAGE_STAGE, mode=0o755)
    for name, digest in package_digest_rows().items():
        dst = os.path.join(PACKAGE_STAGE, name)
        shutil.copyfile(os.path.join(PACKAGE_SRC, name), dst)
        os.chmod(dst, 0o755 if name.endswith(".mjs") else 0o644)
        if sha_file(dst) != digest:
            raise SystemExit("REFUSED: staged %s does not match the evidence-tree bytes" % name)
    os.chmod(PACKAGE_STAGE, 0o755)


def up(env, *args, check=False):
    r = subprocess.run([os.path.join(UPSTREAM, "bin", args[0])] + list(args[1:]),
                       capture_output=True, text=True, env=env)
    if check and r.returncode != 0:
        sys.stdout.write(r.stdout)
        sys.stderr.write(r.stderr)
        raise SystemExit("REFUSED: %s exited %d" % (args[0], r.returncode))
    return r


def modes(path):
    st = os.stat(path)
    return oct(stat.S_IMODE(st.st_mode)), st.st_dev, st.st_nlink


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "show"
    binding = fsc4_config.listener_binding()
    env = dict(os.environ)
    env["FM_HOME"] = binding["home"]
    env["FM_ROOT_OVERRIDE"] = UPSTREAM
    ids = identities(binding)
    if cmd == "show":
        print(json.dumps({"listener": binding, "inbound": ids}, indent=2, sort_keys=True))
        return 0
    if cmd == "retire-gen2":
        r = up(env, "fm-check-unregister.sh", binding["id"])
        sys.stdout.write(r.stdout); sys.stderr.write(r.stderr)
        print("gen2 check unregister exit %d" % r.returncode)
        return r.returncode
    if cmd in ("install", "register"):
        binding, check_path, rec_path, check_sha = install()
        print("listener id     %s" % binding["id"])
        print("check script    %s  mode=%s dev=%s links=%s" % ((check_path,) + modes(check_path)))
        print("record          %s  mode=%s dev=%s links=%s" % ((rec_path,) + modes(rec_path)))
        print("check sha256    %s" % check_sha)
        print("inbound source  %s  (adapter %s, extension %s)" % (ids["source_id"], ids["adapter"], EXTENSION_ID))
        if cmd == "install":
            return 0
        r = up(env, "fm-check-register.sh", binding["id"])
        sys.stdout.write(r.stdout); sys.stderr.write(r.stderr)
        print("check register  exit %d" % r.returncode)
        if r.returncode != 0:
            return r.returncode
        stage_package()
        lst = up(env, "fm-extension.sh", "list")
        if EXTENSION_ID not in lst.stdout:
            r = up(env, "fm-extension.sh", "bind", PACKAGE_STAGE, "--adapter", ids["adapter"],
                   "--trust-same-user-code", "--consent", "network", "--consent", "credential-store",
                   "--timeout-ms", "240000")
            sys.stdout.write(r.stdout); sys.stderr.write(r.stderr)
            print("extension bind  exit %d" % r.returncode)
            if r.returncode != 0:
                return r.returncode
        else:
            print("extension bind  already bound (%s)" % EXTENSION_ID)
        reg = up(env, "fm-procevent.sh", "list")
        if ids["source_id"] in reg.stdout:
            print("source register already registered (%s)" % ids["source_id"])
        else:
            r = up(env, "fm-procevent.sh", "register-extension", ids["adapter"], ids["source_id"],
                   "--config-ref", ids["config_ref"])
            sys.stdout.write(r.stdout); sys.stderr.write(r.stderr)
            print("source register exit %d" % r.returncode)
            if r.returncode != 0:
                return r.returncode
        r = up(env, "fm-procevent.sh", "reconcile")
        sys.stdout.write(r.stdout); sys.stderr.write(r.stderr)
        print("reconcile       exit %d" % r.returncode)
        return 0
    if cmd == "verify":
        check_path, rec_path = binding["check_script_abspath"], binding["record_abspath"]
        bad = 0
        try:
            on_disk = open(check_path, encoding="utf-8").read()
        except OSError as exc:
            print("could-not-observe  check script unreadable: %s" % exc)
            return 7
        ok = on_disk == render_check()
        print("%-18s check script is byte-identical to its rendering from the configuration" % ("observed-good" if ok else "observed-bad"))
        bad += 0 if ok else 1
        sha = hashlib.sha256(on_disk.encode("utf-8")).hexdigest()
        try:
            rec = json.load(open(rec_path, encoding="utf-8"))
        except (OSError, ValueError) as exc:
            print("could-not-observe  listener record unreadable: %s" % exc)
            return 7
        for field, actual in (("listener_id", binding["id"]),
                              ("record_path", binding["record_path"]),
                              ("check_script_path", binding["check_script_path"]),
                              ("check_script_sha256", sha),
                              ("inbound_source_id", ids["source_id"]),
                              ("inbound_adapter", ids["adapter"]),
                              ("inbound_extension_id", EXTENSION_ID),
                              ("inbound_config_ref", ids["config_ref"]),
                              ("inbound_package_files_sha256", package_digest_rows()),
                              ("control_config_generation", fsc4_config.generation()[0]["digest"]),
                              ("resolver_digest", fsc4_config.resolver_digest()),
                              ("schema_sha256", fsc4_config.schema_digest())):
            ok = rec.get(field) == actual
            print("%-18s record.%s equals the value the resolver derives now" % ("observed-good" if ok else "observed-bad", field))
            bad += 0 if ok else 1
        trust = os.path.join(binding["home"], "state", binding["id"] + ".check-trust")
        if os.path.exists(trust):
            lines = open(trust, encoding="utf-8").read().split()
            ok = len(lines) == 2 and lines[1] == sha
            print("%-18s upstream trust binding names the current check-script bytes" % ("observed-good" if ok else "observed-bad"))
            bad += 0 if ok else 1
        else:
            print("could-not-observe  no upstream trust binding present at %s" % trust)
        # the extension binding and its live handshake, through the upstream host
        r = up(env, "fm-extension.sh", "verify", EXTENSION_ID)
        ok = r.returncode == 0
        print("%-18s upstream extension host verifies the bound package and its handshake (exit %d)" % ("observed-good" if ok else "observed-bad", r.returncode))
        bad += 0 if ok else 1
        r = up(env, "fm-procevent.sh", "list")
        ok = ids["source_id"] in r.stdout
        print("%-18s inbound source %s is registered in this home" % ("observed-good" if ok else "observed-bad", ids["source_id"]))
        bad += 0 if ok else 1
        # the supervision predicate: a registered source keeps supervision required
        r = subprocess.run(["bash", "-c", '. "$1/bin/fm-supervision-lib.sh"; fm_supervision_needed "$2/state" && echo needed || echo not-needed',
                            "x", UPSTREAM, binding["home"]], capture_output=True, text=True)
        ok = r.stdout.strip() == "needed"
        print("%-18s upstream supervision predicate reports this home NEEDS a live watcher (%s)" % ("observed-good" if ok else "observed-bad", r.stdout.strip() or r.stderr.strip()[:80]))
        bad += 0 if ok else 1
        print("VERIFY %s" % ("OK" if not bad else "DRIFT: %d predicate(s) not observed-good" % bad))
        return 0 if not bad else 6
    sys.stderr.write(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))

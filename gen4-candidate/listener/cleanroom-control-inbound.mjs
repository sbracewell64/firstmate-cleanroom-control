#!/usr/bin/env node
// Clean-room control listener, INBOUND direction. Control tooling GENERATION 3
// (the protocol string is resolved at runtime, never spelled here). A FirstMate `process-event-adapter/1` extension.
//
// WHY THIS EXISTS (control issue #3, unattended_monitoring = REQUIRED_FOLLOW_ON):
// the generation-2 listener was a watcher custom check that (a) only looked for
// rulings on requests FirstMate had itself emitted and (b) ran only while a
// watcher was alive, and upstream's supervision predicate keeps no watcher alive
// for a bare custom check. So a Browser Sol -> FirstMate commission posted to
// the venue was discovered only when the captain manually woke FirstMate. A
// registered process-event SOURCE is what upstream's predicate does count
// (bin/fm-supervision-lib.sh), so binding this adapter and registering one
// source makes the Stop-owned auto-arm keep a watcher alive with an empty fleet,
// and the watcher's reconcile restarts this poll whenever it returns.
//
// WHAT IT OWNS: discovering fresh QUALIFIED inbound items on the resolved venue
// and handing them to FirstMate as bounded evidence, exactly once per item.
// WHAT IT NEVER OWNS: consuming a ruling, deciding anything, posting anything.
// Every byte it returns is evidence for FirstMate, never authority.
//
// IDENTITY FLOWS FROM THE ONE OWNER. This package names no repository, no
// protocol, no label and no path of its own:
//   adapter name  = <control_config.listener.id>-inbound          (from the host)
//   config_ref    = fm-home:<FM_HOME>                               (registration)
//   listener rec  = <FM_HOME>/<listener.record_path>                (generated by fsc3-listener.py)
//   resolver      = record.resolver                                 (fsc3_config.py)
//   venue         = resolver get control.repository / control.protocol, re-isolated
// If any link in that chain cannot be read, the poll is COULD-NOT-OBSERVE and
// says so out loud (once, then hourly while it persists); it never falls back
// to a remembered venue and never reports "nothing new" over an unobserved venue.
//
// QUALIFIED INBOUND ITEM (one of):
//   inbound_commission  an OPEN issue whose body header reads
//                         protocol_family: <resolved protocol>   (exact string equality)
//                         from: <routing.to>   to: <routing.from>
//                       and every new comment on such an issue that is not
//                       FirstMate's own (an FM->SOL marker or a receipt/request envelope)
//   ruling_candidate    a new comment on an issue that a LIVE outbound request
//                       record (<control root>/state/live/*.json) names
// A closed issue produces nothing. An issue authored by FirstMate's own outbound
// path (routing labels, from: firstmate) is not a commission.
//
// EXACTLY-ONCE SURFACING. The host derives request_id from the registration
// generation and the next uncaptured sequence, so a pre-capture retry reuses the
// id. The ledger under <FM_HOME>/state/<listener.id>.inbound/ records each item
// with the request_id that surfaced it: the same request_id re-emits the same
// items (idempotent replay), a newer request_id never re-announces them.
// Ledger writes are atomic (temp file + rename) on the ext4 home.
//
// BOUNDED. One invocation polls at most POLLS times, POLL_SPACING_MS apart
// (~60 s total, inside the host's default 300 s bound), then returns no-result
// so the host's ordinary reconcile starts the next wait. Forge reads use `gh api`
// with pagination (never a truncating surface) and skip comment fetches for
// issues whose updated_at has not moved since the ledger last saw them.
//
// Protocol: verb `handshake` | `invoke`; one JSON request on stdin, one JSON
// response on stdout; logs on stderr. Operations: source.poll, result.classify,
// result.terminal (always false: this source is ongoing), result.silent (false).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, renameSync, writeFileSync, statSync, readdirSync } from "node:fs";
import path from "node:path";

const EXTENSION_ID = "org.firstmate.cleanroom.control-listener";
const EXTENSION_VERSION = "3.0.0";
const RESULT_SCHEMA = "fm-cleanroom-control-inbound-poll/v1";
const ITEM_SCHEMA = "fm-cleanroom-control-inbound/v1";
const MAX_INPUT_BYTES = 65536;
const MAX_OUTPUT_BYTES = 30000;          // host bound is 32768; keep headroom
const POLLS = Number(process.env.FSC3_INBOUND_POLLS || 2);
const POLL_SPACING_MS = Number(process.env.FSC3_INBOUND_SPACING_MS || 30000);
const CNO_REANNOUNCE_MS = 60 * 60 * 1000;
const MAX_ITEMS = 20;
const FM_MARKERS = ["[FM->SOL]", "[FM→SOL]"];

function log(msg) { process.stderr.write(`${msg}\n`); }
function sha256(text) { return createHash("sha256").update(text, "utf8").digest("hex"); }
function nowIso() { return new Date().toISOString().replace(/\.\d{3}Z$/, "Z"); }

async function readRequest() {
  const chunks = []; let size = 0;
  for await (const chunk of process.stdin) {
    size += chunk.length;
    if (size > MAX_INPUT_BYTES) throw new Error("request is oversized");
    chunks.push(chunk);
  }
  return JSON.parse(Buffer.concat(chunks).toString("utf8"));
}
function reply(requestId, result) {
  process.stdout.write(`${JSON.stringify({ schema: "firstmate.extension-response.v1", request_id: requestId, ok: true, result, error: null })}\n`);
}
function fail(requestId, code, diagnostic, retryable) {
  process.stdout.write(`${JSON.stringify({ schema: "firstmate.extension-response.v1", request_id: requestId, ok: false, result: null,
    error: { code, retryable: Boolean(retryable), diagnostic: String(diagnostic).slice(0, 400) } })}\n`);
}

// ---- the one-owner chain ---------------------------------------------------
function resolveHome(configRef) {
  if (typeof configRef !== "string" || !configRef.startsWith("fm-home:")) throw new Error("config_ref must have the form fm-home:/absolute/home");
  const home = configRef.slice("fm-home:".length);
  if (!path.isAbsolute(home) || path.normalize(home) !== home) throw new Error("config_ref home must be a normalized absolute path");
  return home;
}
function listenerId(adapter) {
  if (typeof adapter !== "string" || !adapter.endsWith("-inbound")) throw new Error("adapter name must be <listener.id>-inbound");
  return adapter.slice(0, -"-inbound".length);
}
function py(resolver, args, home) {
  return execFileSync("python3", [resolver, ...args], { encoding: "utf8", env: { ...process.env, FM_HOME: home }, stdio: ["ignore", "pipe", "pipe"], timeout: 30000 }).trim();
}
function resolveChain(home, adapter) {
  const id = listenerId(adapter);
  const recordPath = path.join(home, "state", `${id}.listener.json`);
  const record = JSON.parse(readFileSync(recordPath, "utf8"));
  if (record.listener_id !== id) throw new Error(`listener record ${recordPath} names ${record.listener_id}, not ${id}`);
  const resolver = record.resolver;
  if (!resolver || !path.isAbsolute(resolver)) throw new Error("listener record carries no absolute resolver path");
  const repo = py(resolver, ["get", "control.repository"], home);
  const proto = py(resolver, ["get", "control.protocol"], home);
  const from = py(resolver, ["get", "routing.from"], home);
  const to = py(resolver, ["get", "routing.to"], home);
  const generation = py(resolver, ["digest"], home);
  if (record.control_config_generation !== generation) throw new Error(`listener record generation ${record.control_config_generation} != resolved ${generation}; regenerate the listener`);
  let admitted = false;
  try { py(resolver, ["isolate", repo, proto], home); admitted = true; } catch { admitted = false; }
  if (!admitted) throw new Error(`venue isolation denied ${repo} ${proto}`);
  const controlRoot = path.dirname(path.dirname(resolver));
  return { id, home, record, resolver, repo, proto, from, to, generation, controlRoot };
}

// ---- durable ledger ---------------------------------------------------------
function ledgerPaths(chain) {
  const dir = path.join(chain.home, "state", `${chain.id}.inbound`);
  return { dir, ledger: path.join(dir, "ledger.json"), register: path.join(dir, "register.json") };
}
function loadLedger(paths) {
  try { return JSON.parse(readFileSync(paths.ledger, "utf8")); }
  catch (e) { if (e.code === "ENOENT") return { schema: "fm-cleanroom-control-inbound-ledger/v1", surfaced: {}, issues_seen: {}, cno: null }; throw e; }
}
function writeAtomic(file, obj) {
  mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
  const tmp = `${file}.${process.pid}.tmp`;
  writeFileSync(tmp, `${JSON.stringify(obj, null, 2)}\n`, { mode: 0o600 });
  renameSync(tmp, file);
}

// ---- forge reads (never a truncating surface) --------------------------------
function gh(args) {
  return execFileSync("gh", ["api", ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], timeout: 60000, maxBuffer: 64 * 1024 * 1024 });
}
function ghPaginated(endpoint) {
  const raw = gh(["--paginate", endpoint]);
  const out = [];
  // gh --paginate concatenates one JSON document per page; each is an array here.
  let depth = 0, start = -1, inStr = false, esc = false;
  for (let i = 0; i < raw.length; i++) {
    const c = raw[i];
    if (inStr) { if (esc) esc = false; else if (c === "\\") esc = true; else if (c === '"') inStr = false; continue; }
    if (c === '"') { inStr = true; continue; }
    if (c === "[" || c === "{") { if (depth === 0) start = i; depth++; }
    else if (c === "]" || c === "}") { depth--; if (depth === 0 && start >= 0) { out.push(...JSON.parse(raw.slice(start, i + 1))); start = -1; } }
  }
  return out;
}

// ---- qualification ------------------------------------------------------------
function headerFields(body) {
  const fields = {};
  for (const line of (body || "").replace(/\r\n/g, "\n").split("\n").slice(0, 40)) {
    const m = /^([a-z_]+):\s*(\S.*)$/.exec(line.trim());
    if (m && !(m[1] in fields)) fields[m[1]] = m[2].trim();
    if (line.trim() === "" && Object.keys(fields).length > 0) break;
  }
  return fields;
}
function fencedKinds(body) {
  const kinds = [];
  const re = /```json[^\n]*\n([\s\S]*?)```/gi;
  let m;
  while ((m = re.exec(body || "")) !== null) {
    try { const o = JSON.parse(m[1]); if (o && typeof o === "object" && typeof o.kind === "string") kinds.push(o.kind); } catch { /* not an envelope */ }
  }
  return kinds;
}
function isFirstmateAuthored(body, chain) {
  const head = (body || "").trimStart();
  if (FM_MARKERS.some((m) => head.startsWith(m))) return true;
  const kinds = fencedKinds(body);
  if (kinds.includes("receipt") || kinds.includes("request")) return true;
  const h = headerFields(body);
  if (h.from === chain.from) return true;
  return false;
}
function commissionHeader(issue, chain) {
  const h = headerFields(issue.body);
  const qualifies = h.protocol_family === chain.proto && h.to === chain.from && h.from === chain.to;
  return { qualifies, h };
}
function liveRequests(chain) {
  const dir = path.join(chain.controlRoot, "state", "live");
  const map = new Map();
  let names = [];
  try { names = readdirSync(dir); } catch (e) { if (e.code !== "ENOENT") throw e; }
  for (const n of names) {
    if (!n.endsWith(".json")) continue;
    try { const rec = JSON.parse(readFileSync(path.join(dir, n), "utf8")); if (rec.issue_number && rec.request_id) map.set(Number(rec.issue_number), rec.request_id); } catch { /* skip */ }
  }
  return map;
}

function item(kind, chain, issueNumber, obj, applicability, requestId) {
  return {
    schema: ITEM_SCHEMA, kind, repository: chain.repo, issue_number: issueNumber,
    item: { id: obj.id, url: obj.html_url },
    author: (obj.user && obj.user.login) || "unknown",
    created_at: obj.created_at,
    body_sha256: sha256(obj.body || ""), body_bytes: Buffer.byteLength(obj.body || "", "utf8"),
    applicability, surfaced_by_request_id: requestId,
  };
}

function pollOnce(chain, ledger, requestId) {
  const issues = ghPaginated(`repos/${chain.repo}/issues?state=open&per_page=100`).filter((i) => !i.pull_request);
  const live = liveRequests(chain);
  const fresh = [];
  const replay = [];
  const register = [];
  for (const issue of issues) {
    const { qualifies, h } = commissionHeader(issue, chain);
    const isLive = live.has(issue.number);
    if (!qualifies && !isLive) continue;
    if (qualifies) register.push({ issue_number: issue.number, url: issue.html_url, title: issue.title, kind: h.kind || null, updated_at: issue.updated_at, comments: issue.comments });
    const issueKey = `issue:${issue.number}`;
    if (qualifies) {
      const prior = ledger.surfaced[issueKey];
      const it = item("issue", chain, issue.number, issue,
        { class: "inbound_commission", protocol_family: h.protocol_family || null, addressed_to: h.to || null, from: h.from || null, ruling_for_request_id: null }, requestId);
      if (!prior) fresh.push(it); else if (prior.request_id === requestId) replay.push(it);
    }
    const seen = ledger.issues_seen[issueKey];
    // A pre-capture retry (same request_id) must re-emit this issue's comments
    // even when the issue has not moved, so a replay is forced to re-read them.
    const replayPending = Object.values(ledger.surfaced).some((e) => e.request_id === requestId && e.issue_number === issue.number);
    const moved = !seen || seen.updated_at !== issue.updated_at || seen.comments !== issue.comments || replayPending;
    if (!moved) continue;
    const comments = ghPaginated(`repos/${chain.repo}/issues/${issue.number}/comments?per_page=100`);
    if (comments.length !== issue.comments) log(`fsc3-inbound: issue #${issue.number} reported ${issue.comments} comments, fetched ${comments.length}; treating the universe as incomplete this poll`);
    for (const c of comments) {
      const key = `comment:${c.id}`;
      if (isFirstmateAuthored(c.body, chain)) { ledger.surfaced[key] = ledger.surfaced[key] || { request_id: "firstmate-authored", skipped: true, sha256: sha256(c.body || "") }; continue; }
      const cls = qualifies && isLive ? "inbound_commission_and_ruling_candidate" : (qualifies ? "inbound_commission" : "ruling_candidate");
      const it = item("comment", chain, issue.number, c,
        { class: cls, protocol_family: qualifies ? (h.protocol_family || null) : null, addressed_to: qualifies ? (h.to || null) : null, from: qualifies ? (h.from || null) : null, ruling_for_request_id: isLive ? live.get(issue.number) : null }, requestId);
      const prior = ledger.surfaced[key];
      if (!prior) fresh.push(it); else if (prior.request_id === requestId) replay.push(it);
    }
    if (comments.length === issue.comments) ledger.issues_seen[issueKey] = { updated_at: issue.updated_at, comments: issue.comments };
  }
  return { fresh, replay, register, issues_scanned: issues.length };
}

async function sourcePoll(request) {
  const requestId = request.request_id;
  let chain, paths, ledger;
  try {
    const home = resolveHome(request.input.config_ref);
    chain = resolveChain(home, request.adapter);
    paths = ledgerPaths(chain);
    ledger = loadLedger(paths);
  } catch (e) {
    // COULD-NOT-OBSERVE, out loud: the venue could not even be resolved.
    return cnoResult(requestId, null, null, `control chain unresolvable: ${e.message}`);
  }
  for (let n = 0; n < POLLS; n++) {
    let polled;
    try { polled = pollOnce(chain, ledger, requestId); }
    catch (e) { return cnoResult(requestId, paths, ledger, `forge unreachable or unparsable: ${String(e.message).split("\n")[0].slice(0, 200)}`); }
    // a successful poll clears any standing CNO episode
    if (ledger.cno) { ledger.cno = null; }
    const items = [...polled.replay, ...polled.fresh];
    writeAtomic(paths.register, { schema: "fm-cleanroom-control-inbound-register/v1", generated_at: nowIso(), repository: chain.repo, protocol: chain.proto,
      open_commissions: polled.register, live_outbound_requests: [...liveRequests(chain)].map(([n, r]) => ({ issue_number: n, request_id: r })) });
    if (items.length > 0) {
      for (const it of polled.fresh) ledger.surfaced[`${it.kind}:${it.kind === "issue" ? it.issue_number : it.item.id}`] = { request_id: requestId, sha256: it.body_sha256, surfaced_at: nowIso(), issue_number: it.issue_number };
      writeAtomic(paths.ledger, ledger);
      return { status: "result", output: bounded({ schema: RESULT_SCHEMA, request_id: requestId, polled_at: nowIso(), repository: chain.repo,
        control_config_generation: chain.generation, verdict: "observed-good", items, replayed: polled.replay.length, fresh: polled.fresh.length,
        summary: `${polled.fresh.length} fresh / ${polled.replay.length} replayed qualified inbound item(s) on ${chain.repo}` }) };
    }
    writeAtomic(paths.ledger, ledger);
    if (n + 1 < POLLS) await new Promise((r) => setTimeout(r, POLL_SPACING_MS));
  }
  return { status: "no-result", output: "" };
}

function cnoResult(requestId, paths, ledger, reason) {
  log(`fsc3-inbound CNO: ${reason}`);
  const now = Date.now();
  if (ledger && paths) {
    const last = ledger.cno && ledger.cno.announced_at ? Date.parse(ledger.cno.announced_at) : 0;
    const since = ledger.cno && ledger.cno.since ? ledger.cno.since : nowIso();
    if (last && now - last < CNO_REANNOUNCE_MS) {
      ledger.cno = { since, announced_at: ledger.cno.announced_at, last_reason: reason };
      writeAtomic(paths.ledger, ledger);
      return { status: "no-result", output: "" };   // already announced within the hour
    }
    ledger.cno = { since, announced_at: nowIso(), last_reason: reason };
    writeAtomic(paths.ledger, ledger);
  }
  return { status: "result", output: bounded({ schema: RESULT_SCHEMA, request_id: requestId, polled_at: nowIso(), verdict: "could-not-observe", items: [], fresh: 0, replayed: 0,
    summary: `COULD-NOT-OBSERVE: ${reason}; the venue was not observed and nothing is known about new inbound work` }) };
}

function bounded(doc) {
  let text = `${JSON.stringify(doc, null, 2)}\n`;
  if (Buffer.byteLength(text, "utf8") <= MAX_OUTPUT_BYTES) return text;
  const trimmed = { ...doc, items: doc.items.slice(0, MAX_ITEMS), truncated_items: doc.items.length - MAX_ITEMS };
  text = `${JSON.stringify(trimmed, null, 2)}\n`;
  while (Buffer.byteLength(text, "utf8") > MAX_OUTPUT_BYTES && trimmed.items.length > 1) {
    trimmed.items.pop(); trimmed.truncated_items += 1; text = `${JSON.stringify(trimmed, null, 2)}\n`;
  }
  return text;
}

function classify(content) {
  try {
    const doc = JSON.parse(content);
    if (doc.schema !== RESULT_SCHEMA) return "unknown";
    if (doc.verdict === "could-not-observe") return "could-not-observe";
    const classes = new Set((doc.items || []).map((i) => i.applicability && i.applicability.class));
    if (classes.size === 0) return "empty";
    if (classes.size === 1) return [...classes][0].replace(/_/g, "-");
    return "mixed";
  } catch { return "unknown"; }
}

const verb = process.argv[2] || "";
const request = await readRequest();
if (verb === "handshake") {
  process.stdout.write(`${JSON.stringify({ schema: "firstmate.extension-handshake-response.v1", request_id: request.request_id,
    extension_id: EXTENSION_ID, extension_version: EXTENSION_VERSION, host_protocol: 1, capability: "process-event-adapter", capability_version: 1,
    adapter_names: request.capability.adapter_names })}\n`);
} else if (verb === "invoke" && request.operation === "source.poll") {
  try { reply(request.request_id, await sourcePoll(request)); }
  catch (e) { fail(request.request_id, "internal", e.message, true); process.exitCode = 1; }
} else if (verb === "invoke" && request.operation === "result.classify") {
  reply(request.request_id, { classification: classify(request.input.content) });
} else if (verb === "invoke" && request.operation === "result.terminal") {
  reply(request.request_id, { value: false });      // an ongoing watch never ends itself
} else if (verb === "invoke" && request.operation === "result.silent") {
  reply(request.request_id, { value: false });      // every captured result reaches firstmate
} else {
  throw new Error("unsupported extension verb or operation");
}
